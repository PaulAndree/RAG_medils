import os
import re
from contextlib import contextmanager
from datetime import datetime, timezone
from time import perf_counter
from uuid import NAMESPACE_URL, uuid4, uuid5

from qdrant_client import QdrantClient, models

from RAG_medils.ingest.indexing.embedding_api import (
    DENSE_MODEL,
    DENSE_VECTOR_SIZE,
    SPARSE_MODEL,
    embed_texts,
)
from RAG_medils.metrics import ProcessMetricSample, push_process_metrics
from RAG_medils.ingest.stores.database_postgres import get_connection, get_indexable_summaries

# Host-side ingestion uses the published port; Compose overrides this URL.
QDRANT_URL = os.getenv("QDRANT_URL", "http://127.0.0.1:6337")
PUSHGATEWAY_URL = os.getenv("PUSHGATEWAY_URL", "http://localhost:9091")

ACTIVE_ALIAS = "summaries_embeddings_live"
COLLECTION_PREFIX = "summaries_embeddings"
DENSE_VECTOR = "dense"
SPARSE_VECTOR = "sparse"

client = QdrantClient(url=QDRANT_URL)
POINT_NAMESPACE = uuid5(
    NAMESPACE_URL,
    "https://learning-1.local/qdrant/summaries",
)


def summary_embedding_text(summary):
    """Include the passage title in level-zero embedding input when present."""

    title = summary.get("title")
    if summary["level"] == 0 and title:
        return f"{title}\n\n{summary['summary_text']}"

    return summary["summary_text"]


def build_collection_name():
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    suffix = uuid4().hex[:8]
    return f"{COLLECTION_PREFIX}_{timestamp}_{suffix}"


def get_alias_target():
    for alias in client.get_aliases().aliases:
        if alias.alias_name == ACTIVE_ALIAS:
            return alias.collection_name

    return None


@contextmanager
def collection_update_lock():
    """Serialize API and CLI rebuilds/cleanup against the same PostgreSQL schema."""
    with get_connection() as connection:
        connection.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(current_schema() || %s, 0))",
            (f':qdrant:{ACTIVE_ALIAS}',),
        )
        yield


def delete_unaliased_collection(collection_name):
    """Delete a generated candidate only when no alias points to it."""
    protected = {alias.collection_name for alias in client.get_aliases().aliases}
    if collection_name in protected or not client.collection_exists(collection_name):
        return
    if not client.delete_collection(collection_name=collection_name):
        raise RuntimeError(f"Could not delete obsolete collection {collection_name}")
    print(f"Deleted unused collection {collection_name}")


def cleanup_unused_collections():
    """Remove obsolete generated indexes while holding collection_update_lock."""
    if get_alias_target() is None:
        raise RuntimeError(f"Refusing cleanup without the {ACTIVE_ALIAS} alias")
    # Match only the names generated by build_collection_name().
    pattern = rf"{re.escape(COLLECTION_PREFIX)}_\d{{8}}T\d{{6}}Z_[0-9a-f]{{8}}"
    for collection in client.get_collections().collections:
        if re.fullmatch(pattern, collection.name):
            delete_unaliased_collection(collection.name)


def create_collection(collection_name):
    client.create_collection(
        collection_name=collection_name,
        vectors_config={
            DENSE_VECTOR: models.VectorParams(
                size=DENSE_VECTOR_SIZE,
                distance=models.Distance.COSINE,
            ),
        },
        sparse_vectors_config={
            SPARSE_VECTOR: models.SparseVectorParams(),
        },
    )

    client.create_payload_index(
        collection_name=collection_name,
        field_name="catalog_id",
        field_schema=models.PayloadSchemaType.KEYWORD,
        wait=True,
    )

    print(
        f"Created collection {collection_name} "
        f"with vector size {DENSE_VECTOR_SIZE}"
    )


def index_summaries(collection_name, summaries):
    ids = []
    vectors = []
    payloads = []
    texts = [summary_embedding_text(summary) for summary in summaries]
    dense_vectors = embed_texts(texts, DENSE_MODEL)
    sparse_vectors = embed_texts(texts, SPARSE_MODEL)

    for each_summary, dense_vector, sparse_vector in zip(
        summaries,
        dense_vectors,
        sparse_vectors,
        strict=True,
    ):

        ids.append(str(uuid5(
            POINT_NAMESPACE,
            each_summary["node_id"],
        )))

        vectors.append({
            DENSE_VECTOR: dense_vector,
            SPARSE_VECTOR: models.SparseVector(
                indices=sparse_vector["indices"],
                values=sparse_vector["values"],
            ),
        })

        payloads.append(
            {
                "node_id": each_summary["node_id"],
                "summary_text": each_summary["summary_text"],
                "level": each_summary["level"],
                "scope": each_summary["scope"],
                "createdDateTime": (
                    each_summary["createdDateTime"].isoformat()
                    if each_summary["createdDateTime"] is not None else None
                ),
                "modifiedDateTime": (
                    each_summary["modifiedDateTime"].isoformat()
                    if each_summary["modifiedDateTime"] is not None else None
                ),
                "document_id": each_summary["document_id"],
                "document_title": each_summary["document_title"],
                "catalog_id": each_summary["catalog_id"],
                "source_key": each_summary["source_key"],
                "chunk_index": each_summary["chunk_index"],
                "title": each_summary["title"],
                "token_count": each_summary["token_count"],
                "source_node_ids": each_summary["source_node_ids"],
                "source_chunk_ids": each_summary["source_chunk_ids"],
                "source_document_ids": each_summary["source_document_ids"],
            }
        )

    client.upload_collection(
        collection_name=collection_name,
        vectors=vectors,
        payload=payloads,
        ids=ids,
        wait=True,
    )

    print(f"Indexed {len(summaries)} summaries into {collection_name}")


def validate_collection(collection_name, summaries):
    indexed_count = client.count(
        collection_name=collection_name,
        exact=True,
    ).count

    if indexed_count != len(summaries):
        raise RuntimeError(
            f"Validation failed for {collection_name}: "
            f"expected {len(summaries)} points, "
            f"found {indexed_count}"
        )

    text = summary_embedding_text(summaries[0])
    dense_query = embed_texts([text], DENSE_MODEL, "query")[0]
    sparse_query = embed_texts([text], SPARSE_MODEL, "query")[0]

    smoke_result = client.query_points(
        collection_name=collection_name,
        prefetch=[
            models.Prefetch(
                query=dense_query,
                using=DENSE_VECTOR,
                limit=10,
            ),
            models.Prefetch(
                query=models.SparseVector(
                    indices=sparse_query["indices"],
                    values=sparse_query["values"],
                ),
                using=SPARSE_VECTOR,
                limit=10,
            ),
        ],
        query=models.FusionQuery(fusion=models.Fusion.RRF),
        limit=1,
        with_payload=True,
    )

    if not smoke_result.points:
        raise RuntimeError(
            f"Validation failed for {collection_name}: "
            "smoke query returned no results"
        )

    print(f"Validated collection {collection_name}")


def activate_collection(collection_name, previous_collection):
    operations = []

    if previous_collection is not None:
        operations.append(
            models.DeleteAliasOperation(
                delete_alias=models.DeleteAlias(alias_name=ACTIVE_ALIAS)
            )
        )

    operations.append(
        models.CreateAliasOperation(
            create_alias=models.CreateAlias(
                collection_name=collection_name,
                alias_name=ACTIVE_ALIAS,
            )
        )
    )

    client.update_collection_aliases(
        change_aliases_operations=operations,
    )

    if get_alias_target() != collection_name:
        raise RuntimeError(
            f"Alias {ACTIVE_ALIAS} was not activated for {collection_name}"
        )

    print(f"Alias {ACTIVE_ALIAS} now points to {collection_name}")


def _rebuild_index():
    started = perf_counter()
    summaries = get_indexable_summaries()

    if not summaries:
        raise RuntimeError(
            "No PostgreSQL summaries were found; "
            "refusing to activate an empty index"
        )

    new_collection = build_collection_name()
    previous_collection = get_alias_target()

    print(f"Building new collection {new_collection}")

    if previous_collection is not None:
        print(f"Current alias target is {previous_collection}")

    try:
        create_collection(new_collection)
        index_summaries(new_collection, summaries)
        validate_collection(new_collection, summaries)
        activate_collection(
            new_collection,
            previous_collection,
        )
    except Exception:
        # An activation request can succeed remotely before its response fails.
        # Recheck aliases so the newly active collection is never deleted.
        try:
            delete_unaliased_collection(new_collection)
        except Exception as cleanup_error:
            print(f"[indexing] could not clean up {new_collection}: {cleanup_error}")
        raise

    cleanup_unused_collections()

    source_document_ids = set()
    for summary in summaries:
        if summary["document_id"] is not None:
            source_document_ids.add(str(summary["document_id"]))
        source_document_ids.update(summary["source_document_ids"])

    try:
        push_process_metrics(
            process="indexing",
            samples=[ProcessMetricSample(
                representation="summaries",
                document_count=len(source_document_ids),
                item_counts={"summaries": len(summaries)},
                duration_seconds=perf_counter() - started,
            )],
            pushgateway_url=PUSHGATEWAY_URL,
            job="indexing_summaries",
        )
    except Exception as exc:
        print(f"[indexing] warning: could not publish metrics: {exc}")


def main():
    with collection_update_lock():
        _rebuild_index()


if __name__ == "__main__":
    main()
